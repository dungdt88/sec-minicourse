// Writes deploy/supabase-schema.sql: every migration in order, in one transaction, for pasting
// into a hosted project's SQL Editor (production is a Supabase project shared with other apps,
// where `supabase db push` is not used). A unit test fails if the file is out of date.
//
//   pnpm gen:schema-sql
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = 'supabase/migrations';
export const SCHEMA_SQL_FILE = 'deploy/supabase-schema.sql';

export function schemaSql(): string {
  const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
  const parts = files.map((f) => ({ f, sql: readFileSync(`${dir}/${f}`, 'utf8') }));
  const sha = (s: string) => createHash('sha256').update(s).digest('hex');
  return [
    '-- Tiệm Vòng Tay Rừng Xanh: the full database schema, for a Supabase project that does not have',
    '-- the sec_minicourse schema yet (the project may be shared with other apps).',
    '--',
    '-- Supabase Dashboard → SQL Editor → New query → paste this file → Run. It runs as one',
    '-- transaction, so it applies completely or not at all; if sec_minicourse already exists it',
    '-- stops at "create schema" and changes nothing. It creates the schema sec_minicourse and',
    "-- everything in it (tables, row-level security, functions, grants), touches nothing in public",
    "-- or any other app's schema, and inserts no data.",
    '-- Then: Project Settings → Data API → Exposed schemas → add sec_minicourse.',
    '--',
    `-- Generated by scripts/build-schema-sql.ts from ${files.length} migrations (sha256):`,
    ...parts.map(({ f, sql }) => `--   ${f}  ${sha(sql)}`),
    '',
    'begin;',
    '',
    ...parts.flatMap(({ f, sql }) => [`-- ${'='.repeat(70)}`, `-- ${f}`, `-- ${'='.repeat(70)}`, sql.trimEnd(), '']),
    'commit;',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(SCHEMA_SQL_FILE, schemaSql());
  console.log(`wrote ${SCHEMA_SQL_FILE}`);
}
